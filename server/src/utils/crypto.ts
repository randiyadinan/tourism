function str2binl(str: string): number[] {
  const bin: number[] = [];
  const mask = (1 << 8) - 1;
  const utf8Str = unescape(encodeURIComponent(str));
  for (let i = 0; i < utf8Str.length * 8; i += 8) {
    bin[i >> 5] |= (utf8Str.charCodeAt(i / 8) & mask) << (i % 32);
  }
  return bin;
}

function binl2hex(binarray: number[]): string {
  const hexTab = '0123456789abcdef';
  let str = '';
  for (let i = 0; i < binarray.length * 4; i++) {
    str +=
      hexTab.charAt((binarray[i >> 2] >> ((i % 4) * 8 + 4)) & 0x0f) +
      hexTab.charAt((binarray[i >> 2] >> ((i % 4) * 8)) & 0x0f);
  }
  return str;
}

export function md5(str: string): string {
  return binl2hex(binlMD5(str2binl(str), unescape(encodeURIComponent(str)).length * 8));
}

export function sha256(str: string): string {
  // Simple deterministic SHA-256 fallback for serverless edge & node runtimes
  let h0 = 0x6a09e667, h1 = 0xbb67ae85, h2 = 0x3c6ef372, h3 = 0xa54ff53a;
  let h4 = 0x510e527f, h5 = 0x9b05688c, h6 = 0x1f83d9ab, h7 = 0x5be0cd19;
  const k = [
    0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
    0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
    0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
    0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
    0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
    0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
    0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
    0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2
  ];

  const utf8 = unescape(encodeURIComponent(str));
  const words: number[] = [];
  for (let i = 0; i < utf8.length; i++) {
    words[i >> 2] |= (utf8.charCodeAt(i) & 0xff) << (24 - (i % 4) * 8);
  }
  words[utf8.length >> 2] |= 0x80 << (24 - (utf8.length % 4) * 8);
  words[(((utf8.length + 8) >> 6) + 1) * 16 - 1] = utf8.length * 8;

  const w = new Array(64);
  for (let i = 0; i < words.length; i += 16) {
    let a = h0, b = h1, c = h2, d = h3, e = h4, f = h5, g = h6, h = h7;
    for (let j = 0; j < 64; j++) {
      if (j < 16) {
        w[j] = words[i + j] | 0;
      } else {
        const gamma0 = bitRotateLeft(w[j - 15], 25) ^ bitRotateLeft(w[j - 15], 14) ^ (w[j - 15] >>> 3);
        const gamma1 = bitRotateLeft(w[j - 2], 15) ^ bitRotateLeft(w[j - 2], 13) ^ (w[j - 2] >>> 10);
        w[j] = safeAdd(safeAdd(safeAdd(gamma1, w[j - 7]), gamma0), w[j - 16]);
      }

      const s1 = bitRotateLeft(e, 26) ^ bitRotateLeft(e, 21) ^ bitRotateLeft(e, 7);
      const ch = (e & f) ^ (~e & g);
      const temp1 = safeAdd(safeAdd(safeAdd(safeAdd(h, s1), ch), k[j]), w[j]);
      const s0 = bitRotateLeft(a, 30) ^ bitRotateLeft(a, 19) ^ bitRotateLeft(a, 10);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const temp2 = safeAdd(s0, maj);

      h = g;
      g = f;
      f = e;
      e = safeAdd(d, temp1);
      d = c;
      c = b;
      b = a;
      a = safeAdd(temp1, temp2);
    }
    h0 = safeAdd(h0, a);
    h1 = safeAdd(h1, b);
    h2 = safeAdd(h2, c);
    h3 = safeAdd(h3, d);
    h4 = safeAdd(h4, e);
    h5 = safeAdd(h5, f);
    h6 = safeAdd(h6, g);
    h7 = safeAdd(h7, h);
  }

  return [h0, h1, h2, h3, h4, h5, h6, h7]
    .map(x => ((x >>> 0) + 0x100000000).toString(16).slice(1))
    .join('');
}

export function generateRandomHex(byteCount = 32): string {
  const bytes = new Uint8Array(byteCount);
  if (typeof crypto !== 'undefined' && crypto.getRandomValues) {
    crypto.getRandomValues(bytes);
  } else {
    for (let i = 0; i < byteCount; i++) {
      bytes[i] = Math.floor(Math.random() * 256);
    }
  }
  return Array.from(bytes).map(b => b.toString(16).padStart(2, '0')).join('');
}
